using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;
using PySharp.SourceGeneration.Utility;
using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace PySharp.SourceGeneration;

[Generator]
public class SlotsGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var provider = context.SyntaxProvider
            .ForAttributeWithMetadataName(
                fullyQualifiedMetadataName: PySharpTypes.PyTypeAttribute,
                predicate: static (syntaxNode, _) => syntaxNode is ClassDeclarationSyntax,
                transform: static (generatorContext, _) =>
                {
                    var typeSymbol = (INamedTypeSymbol)generatorContext.TargetSymbol;
                    var overridenSlots = new List<string>();

                    foreach (var member in typeSymbol.GetMembers())
                    {
                        if (member is not IMethodSymbol methodSymbol)
                            continue;

                        if (methodSymbol.IsDefined(PySharpTypes.PySlotAttribute, inherit: true))
                            overridenSlots.Add(methodSymbol.Name);
                    }

                    return new PyType(typeSymbol.ContainingNamespace.IsGlobalNamespace ? string.Empty : typeSymbol.ContainingNamespace.ToDisplayString(),
                        typeSymbol.Name, overridenSlots);
                });

        context.RegisterSourceOutput(provider, (spc, pyType) =>
        {
            if (pyType.Slots.Count is 0)
                return;

            var builder = new IndentedStringBuilder();
            builder.AppendLine("// <auto-generated/>");
            builder.AppendLine("using System;");
            builder.AppendLine("using PySharp.Runtime;");

            builder
                .AppendLine($"namespace {pyType.Namespace}")
                .EnterBlock()
                    .AppendLine($"partial class {pyType.Name}")
                    .EnterBlock()
                        .AppendLine("protected override void FillSlots()")
                        .EnterBlock()
                            .ForEach(pyType.Slots, (builder, slot) =>
                            {
                                builder.AppendLine($"FillSlot(PySpecialNames.{slot}, ref Slots.{slot}, {slot});");
                            })
                        .ExitBlock()
                    .ExitBlock()
                .ExitBlock();

            spc.AddSource($"{pyType.Name}.Slots.g.cs", SourceText.From(builder.ToString(), Encoding.UTF8));
        });
    }

    public class PyType
    {
        public PyType(string @namespace, string name, List<string> slots)
        {
            Namespace = @namespace;
            Name = name;
            Slots = slots;
        }

        public string Namespace { get;}
        public string Name { get; }
        public List<string> Slots { get; }
    }
}

